import math
import warnings
from fractions import Fraction

import numpy as np
from spglib import get_symmetry_dataset

__author__ = "Artem Dembitskiy"


# Denominators that crystallographic translations can have
# (centering vectors and screw/glide components in any standard setting).
_ALLOWED_DENOMINATORS = (1, 2, 3, 4, 6, 8, 12)


def _snap_translation(t, tol):
    """
    Snap fractional translation components to k/d with d from _ALLOWED_DENOMINATORS.

    Returns
    -------
    fractions: list of Fraction or None
        None if any component cannot be represented within `tol`.
    """
    snapped = []
    for x, eps in zip(np.mod(t, 1.0), tol):
        frac = Fraction(float(x)).limit_denominator(max(_ALLOWED_DENOMINATORS))
        if frac.denominator not in _ALLOWED_DENOMINATORS or abs(float(frac) - x) > eps:
            # try once more around the wrap-around point (x ~ 1.0 -> 0)
            if abs(x - 1.0) <= eps:
                frac = Fraction(0)
            else:
                return None
        snapped.append(frac % 1)
    return snapped


def _coupled_axes(rotations):
    """Group axes that are mixed by any rotation (they must share the same mesh size)."""
    parent = [0, 1, 2]

    def find(i):
        while parent[i] != i:
            i = parent[i]
        return i

    for R in rotations:
        for i in range(3):
            for j in range(3):
                if i != j and R[i, j] != 0:
                    parent[find(i)] = find(j)
    groups = {}
    for i in range(3):
        groups.setdefault(find(i), []).append(i)
    return list(groups.values())


def commensurate_mesh_shape(base_shape, rotations, translations):
    """
    Smallest mesh shape >= base_shape on which all operations map grid points onto grid points.

    Axes coupled by a rotation get the same number of points, and the number of points along
    each axis is a multiple of the denominators of the translations along that axis.
    """
    base_shape = [max(1, int(n)) for n in base_shape]
    shape = list(base_shape)
    for group in _coupled_axes(rotations):
        n = max(base_shape[i] for i in group)
        m = 1
        for t in translations:
            for i in group:
                m = math.lcm(m, Fraction(t[i]).denominator)
        n = int(math.ceil(n / m) * m)
        for i in group:
            shape[i] = n
    return tuple(shape)


class Mesh:
    """
    Periodic mesh of a unit cell and its symmetry-irreducible points.

    Mesh point (i, j, k) sits at fractional coordinates (i/nx, j/ny, k/nz),
    i.e. the mesh is periodic and does not repeat the boundary plane.

    Example
    -------

    mesh = Mesh.from_atoms(atoms, resolution = 0.2, symprec = 0.1)
    ir_grid_points, mapping = mesh.get_irreducible_mapping()

    """

    def __init__(self, mesh_shape, rotations, translations, symmetry_dataset=None):
        """
        Initialization.

        Parameters
        ----------

        mesh_shape: tuple of integers, (nx, ny, nz)
            shape of the mesh

        rotations: list of numpy arrays of shape (3, 3)
            rotation matrices (fractional coordinates)

        translations: list of numpy arrays of shape (3,)
            translation vectors (fractional coordinates)
            Operations that do not map the mesh onto itself are dropped with a warning.

        symmetry_dataset: dict generated by spglib library, None by default (Optional)
            dataset containing symmetry operations, used for tests
        """

        self.mesh_shape = tuple(int(n) for n in mesh_shape)
        self.symmetry_dataset = symmetry_dataset
        self.rotations, self.translations, self.n_dropped = self._valid_ops(rotations, translations)
        if self.n_dropped:
            warnings.warn(
                f"{self.n_dropped} of {len(rotations)} symmetry operations are not commensurate "
                f"with mesh {self.mesh_shape} and were ignored. The result is still exact, "
                "but fewer points are symmetry-reduced.",
                UserWarning,
                stacklevel=2,
            )
        self.mesh = self._generate_mesh()

    @property
    def addresses(self):
        return self.mesh

    @property
    def frac_coords(self):
        return self.mesh / np.asarray(self.mesh_shape)

    @staticmethod
    def _spglib_types(atoms):
        """Atomic numbers, refined by oxidation states if present (charge ordering breaks symmetry)."""
        if "oxi_states" not in atoms.arrays:
            return atoms.numbers
        pairs = np.stack([atoms.numbers, np.asarray(atoms.arrays["oxi_states"], dtype=float)], axis=1)
        _, types = np.unique(pairs, axis=0, return_inverse=True)
        return types.ravel() + 1

    @classmethod
    def from_atoms(cls, atoms, resolution=0.2, symprec=None):
        """
        Create Mesh object form ASE's Atoms object.

        Parameters
        ----------

        atoms: ASE's Atoms object
            atomic structure
            if atoms.arrays["oxi_states"] exists, it is used to distinguish atoms of the same element

        resolution: float, 0.2 by default
            approximate distance between points of the mesh in angstroms
            the actual number of points can be slightly increased
            to make the mesh commensurate with symmetry operations

        symprec: None or float, None by default
            symmetry precision
            used by spglib' get_symmetry_dataset to find symmetry operations
        """

        lengths = np.linalg.norm(np.asarray(atoms.cell), axis=1)
        base_shape = [max(1, int(length // resolution)) for length in lengths]

        rotations = [np.eye(3, dtype=int)]
        translations = [np.zeros(3)]
        symmetry_dataset = None

        if symprec:
            spglib_cell = (np.asarray(atoms.cell), atoms.get_scaled_positions(), cls._spglib_types(atoms))
            symmetry_dataset = get_symmetry_dataset(spglib_cell, symprec=symprec)
            if symmetry_dataset is not None:
                tol = np.maximum(symprec / lengths, 1e-5)
                rotations, translations = [], []
                for R, t in zip(symmetry_dataset.rotations, symmetry_dataset.translations):
                    snapped = _snap_translation(t, tol)
                    if snapped is None:
                        continue  # dropped (with a warning) in __init__
                    rotations.append(R)
                    translations.append(snapped)
                n_irrational = len(symmetry_dataset.rotations) - len(rotations)
                if n_irrational:
                    warnings.warn(
                        f"{n_irrational} symmetry operations have translations that cannot be put "
                        "on a mesh (non-standard origin?) and were ignored.",
                        UserWarning,
                        stacklevel=2,
                    )

        mesh_shape = commensurate_mesh_shape(base_shape, rotations, translations)
        translations = [np.array([float(x) for x in t]) for t in translations]
        return cls(mesh_shape, rotations, translations, symmetry_dataset=symmetry_dataset)

    def _valid_ops(self, rotations, translations):
        """Keep operations that map integer mesh points exactly onto integer mesh points."""
        n = np.asarray(self.mesh_shape)
        kept_R, kept_t = [], []
        for R, t in zip(rotations, translations):
            R = np.asarray(R, dtype=int)
            t = np.asarray(t, dtype=float)
            # R must not mix axes with different numbers of points
            mixes = (R != 0) & (n[:, None] != n[None, :])
            t_idx = t * n
            if mixes.any() or not np.allclose(t_idx, np.rint(t_idx), atol=1e-6):
                continue
            kept_R.append(R)
            kept_t.append(np.rint(t_idx).astype(int))
        if not kept_R:
            kept_R, kept_t = [np.eye(3, dtype=int)], [np.zeros(3, dtype=int)]
        return kept_R, kept_t, len(rotations) - len(kept_R)

    def _generate_mesh(self):
        """Generate integer grid points (i,j,k) of the periodic mesh."""
        grid = np.mgrid[
            0:self.mesh_shape[0],
            0:self.mesh_shape[1],
            0:self.mesh_shape[2]
        ].reshape(3, -1).T
        return grid  # shape (N,3), integer

    def _index_to_linear(self, indices):
        """Convert 3D integer indices -> 1D linear indices for fast lookup."""
        return np.ravel_multi_index(indices.T, self.mesh_shape)

    def _image(self, R, t_idx):
        """Linear indices of the images of all mesh points under (R, t)."""
        transformed = (self.mesh @ R.T + t_idx) % np.asarray(self.mesh_shape)
        return self._index_to_linear(transformed)

    def get_irreducible_mapping(self):
        """
        Find symmetry-equivalent points on an integer 3D mesh.

        Each point is labeled with the smallest mesh index in its orbit. Labels are
        propagated through the operations until nothing changes, so the result is
        exact for any set of valid operations (it does not have to be a closed group;
        for a full group one pass is enough). Memory is O(number of points).

        Returns
        -------
        indices of the irreducible points of the mesh and
        mapping indices to restore full mesh from irreducible points

        """
        npoints = len(self.mesh)
        labels = np.arange(npoints)
        images = None
        if len(self.rotations) * npoints <= 20_000_000:  # cache images up to ~160 MB
            images = [self._image(R, t) for R, t in zip(self.rotations, self.translations)]

        while True:
            changed = False
            for i, (R, t_idx) in enumerate(zip(self.rotations, self.translations)):
                img = images[i] if images is not None else self._image(R, t_idx)
                # point p and its image g(p) belong to one orbit
                new = np.minimum(labels, labels[img])
                new[img] = np.minimum(new[img], new)  # push to g(p) too; img is a permutation
                if not changed and not np.array_equal(new, labels):
                    changed = True
                labels = new
            # pointer jumping: label of a label
            jumped = labels[labels]
            if not np.array_equal(jumped, labels):
                labels, changed = jumped, True
            if not changed:
                break

        ir_grid_points, mapping = np.unique(labels, return_inverse=True)
        return ir_grid_points, mapping.ravel()
